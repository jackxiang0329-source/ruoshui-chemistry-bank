#!/usr/bin/env node
// CC BY NVIDIA chemistry RQA: raw synthetic AI text staged for HUMAN REVIEW ONLY.
// Never insert into data/candidates/ or any published question index.
import {readFileSync,writeFileSync,existsSync,readdirSync,mkdirSync,appendFileSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const ROOT=dirname(dirname(fileURLToPath(import.meta.url)));
const CFG=join(ROOT,'harvest','pinned_nvidia_science_rqa.json');
const STATE=join(ROOT,'harvest','nvidia_rqa_state.json');
const DIR=join(ROOT,'data','research_quarantine','nvidia-rqa');
export const questionHash=text=>createHash('sha256').update(String(text).normalize('NFKC').replace(/\s+/g,' ').trim().toLowerCase()).digest('hex');
export function inferSubject(q){
 const s=String(q).toLowerCase(),hit=[];
 if(/analytical|titration|chromatograph|spectrophotometr|calibration curve|quantitative analysis|gravimetr/.test(s))hit.push('analytical');
 if(/thermodynamic|reaction kinetics|reaction rate constant|electrochem|enthalpy|entropy|gibbs free energy|van.t hoff|photophysic|quantum chem/.test(s))hit.push('physical');
 if(/organometal|inorganic|coordination complex|ligand field|crystal field|transition metal complex/.test(s))hit.push('inorganic');
 if(/organic synthesis|stereochem|enantioselectiv|nucleophilic substitution|cycloaddition|regioselectiv/.test(s))hit.push('organic');
 return hit.length===1?hit[0]:'needs_manual_classification';
}
export function curatePage(page,config,seen){
 if(!Array.isArray(page))throw Error('Invalid source page');
 const rows=[],excluded={};
 const skip=key=>excluded[key]=(excluded[key]||0)+1;
 for(const obj of page){
  const r=obj?.row||{},m=r.messages||[],n=obj?.row_idx;
  if(!Number.isSafeInteger(n)||n<0||obj.truncated_cells?.length){skip('invalid_or_truncated');continue;}
  if(r.license!=='cc-by-4.0'){skip('license_not_verified');continue;}
  if(!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(r.uuid||'')){skip('uuid_invalid');continue;}
  if(!Array.isArray(m)||m.length!==2||m[0]?.role!=='user'||m[1]?.role!=='assistant'){skip('unexpected_chat_schema');continue;}
  const q=m[0].content,a=m[1].content;
  if(typeof q!=='string'||typeof a!=='string'||q.length<100||q.length>config.max_question_chars||
    a.length<30||a.length>config.max_answer_chars){skip('answer_or_question_length');continue;}
  if(/<svg\b|<img\b|data:image\/|!\[[^\]]*\]\(https?:/i.test(q+'\n'+a)){skip('media_needs_additional_rights');continue;}
  const sha=questionHash(q);
  if(seen.has(sha)){skip('duplicate_question');continue;}
  seen.add(sha);
  rows.push({schema_version:1,uuid:r.uuid,source_row:n,question:q,unverified_model_answer:a,
   question_sha256:sha,subject_suggestion:inferSubject(q),
   kind:'synthetic_research_qa',quality_status:'not_scientifically_verified',
   publishable:false,exclude_from_official_bank:true,requires_expert_review:true,
   provenance:{dataset:config.dataset,revision:config.revision,split:'RQA',
    row_license:'CC BY 4.0',author:'NVIDIA Corporation',
    url:'https://huggingface.co/datasets/'+config.dataset,
    disclaimer:'Generated by an LLM; chemical reasoning and answer NOT independently validated.'}});
 }
 return {rows,excluded};
}
export function readArchive(){
 const seen=new Set(),ids=new Set();let total=0;
 if(existsSync(DIR))for(const file of readdirSync(DIR)){
  if(!/^\d{6}-\d{6}\.jsonl$/.test(file))continue;
  for(const line of readFileSync(join(DIR,file),'utf8').split('\n')){
   if(!line.trim())continue;
   const v=JSON.parse(line);
   if(v.publishable!==false||v.exclude_from_official_bank!==true||!v.question_sha256)throw Error('Unsafe earlier staged row');
   seen.add(v.question_sha256);ids.add(v.uuid);total++;
  }
 }
 return {seen,ids,total};
}
async function request(url){
 const r=await fetch(url,{signal:AbortSignal.timeout(30000),
  headers:{Accept:'application/json','User-Agent':'ruoshui-chemistry-scientific-qa-audit'}});
 if(!r.ok)throw Error('Source API HTTP '+r.status+' on '+new URL(url).pathname);
 return r.json();
}
export async function run(fetchJSON=request){
 const cfg=JSON.parse(readFileSync(CFG,'utf8'));
 if(cfg.schema_version!==1||cfg.dataset!=='nvidia/Nemotron-Science-v1'||
  cfg.revision!=='82e1af468197076b4f0f392c239274eac032adc7'||
  cfg.license!=='cc-by-4.0'||cfg.config!=='default'||cfg.split!=='RQA'||cfg.total_rows!==52179||
  !Number.isInteger(cfg.batch_pages)||cfg.batch_pages<1||cfg.batch_pages>10||
  cfg.page_size<1||cfg.page_size>100||cfg.max_staged<100||cfg.max_staged>10000)
  throw Error('Unapproved source pin, split or size limit');
 const state=existsSync(STATE)?JSON.parse(readFileSync(STATE,'utf8')):
  {schema_version:1,revision:cfg.revision,next_offset:0,examined:0};
 if(state.revision!==cfg.revision||state.schema_version!==1||!Number.isSafeInteger(state.next_offset))
  throw Error('Source cursor needs manual reconciliation');
 const {seen,ids,total}=readArchive();
 if(total>=cfg.max_staged){console.log('Research quarantine cap reached: '+total);return {added:0,total};}
 const metadata=await fetchJSON('https://huggingface.co/api/datasets/'+cfg.dataset);
 if(metadata.sha!==cfg.revision||metadata.cardData?.license!=='cc-by-4.0')throw Error('Dataset SHA or content license drift');
 const splits=await fetchJSON('https://datasets-server.huggingface.co/splits?dataset='+encodeURIComponent(cfg.dataset));
 if(!splits.splits?.some(x=>x.config==='default'&&x.split==='RQA'))
  throw Error('RQA source split rows changed; fail closed');
 let offset=state.next_offset,accepted=[],reject={},pageCount=0;
 const start=offset;
 const pages=Math.min(cfg.batch_pages,Math.ceil((cfg.max_staged-total)/cfg.page_size));
 for(let i=0;i<pages&&offset<cfg.total_rows;i++){
  const url=new URL('https://datasets-server.huggingface.co/rows');
  for(const [k,v] of Object.entries({dataset:cfg.dataset,config:'default',split:'RQA',offset,
   length:Math.min(cfg.page_size,cfg.total_rows-offset)}))url.searchParams.set(k,String(v));
  const page=await fetchJSON(String(url));
  if(page.partial||!Array.isArray(page.rows)||page.rows.length===0)throw Error('Empty or truncated source page');
  if(page.num_rows_total!==cfg.total_rows)throw Error('RQA rows total changed or missing; abort without writing');
  if(page.rows.some((x,j)=>x.row_idx!==offset+j))throw Error('Dataset offset shifted unexpectedly');
  const processed=curatePage(page.rows,cfg,seen);
  for(const [k,v] of Object.entries(processed.excluded))reject[k]=(reject[k]||0)+v;
  for(const q of processed.rows)if(ids.has(q.uuid)){reject.duplicate_uuid=(reject.duplicate_uuid||0)+1;}else{accepted.push(q);ids.add(q.uuid);}
  offset+=page.rows.length;pageCount++;
 }
 mkdirSync(DIR,{recursive:true});
 if(accepted.length){
  const file=join(DIR,String(start).padStart(6,'0')+'-'+String(offset-1).padStart(6,'0')+'.jsonl');
  if(existsSync(file))throw Error('Quarantine shard already exists; abort');
  writeFileSync(file,accepted.map(x=>JSON.stringify(x)).join('\n')+'\n');
 }
 Object.assign(state,{next_offset:offset,examined:(state.examined||0)+(offset-start),
  staged_total:total+accepted.length,last_add:accepted.length,last_examined:offset-start,last_pages:pageCount,
  last_rejected:reject});
 writeFileSync(STATE,JSON.stringify(state,null,2)+'\n');
 const msg='NVIDIA RQA staging: source examined='+ (offset-start)+
  '; NEW UNVERIFIED QA='+accepted.length+'; total quarantined='+state.staged_total+
  '; official published questions added=0; rejected='+JSON.stringify(reject);
 console.log(msg);
 if(process.env.GITHUB_STEP_SUMMARY)appendFileSync(process.env.GITHUB_STEP_SUMMARY,msg+'\n');
 return {added:accepted.length,total:state.staged_total};
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 run().catch(e=>{console.error(e.stack);process.exitCode=1;});
}
