#!/usr/bin/env node
// README candidate totals are derived ONLY from synchronized, unapproved audit data.
import {readFileSync,writeFileSync} from 'node:fs';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const ROOT=dirname(dirname(fileURLToPath(import.meta.url)));
const fmt=x=>x.toLocaleString('en-US');
export function snapshot(q,v){
 const n=q?.total_candidates,s=q?.by_subject||{},k=q?.by_content_kind||{};
 const sum=['inorganic','analytical','organic','physical'].reduce((a,key)=>a+(s[key]||0),0);
 if(!Number.isInteger(n)||n<0||sum!==n||
   !['inorganic','analytical','organic','physical'].every(z=>Number.isInteger(s[z])&&s[z]>=0)||
   !Number.isInteger(k.exercise_candidate)||!Number.isInteger(k.study_card)||
   k.exercise_candidate+k.study_card!==n||
   q?.by_quality_status?.awaiting_expert_review!==n||q?.by_publishable?.false!==n||
   q?.expert_approved_publishable_count!==0||v?.confirmed_official_exam_ready!==0||
   v?.main_candidate_records!==n||v?.main_exercise_candidates!==k.exercise_candidate||
   v?.main_unique_candidate_records_machine_replayed!==n)
  throw Error('Inconsistent or unreviewed chemistry audit ledger; README update refused');
 return [
 '## 当前候选内容快照（由 CI 审核数据自动同步）','',
 '<!-- GENERATED BY scripts/update-chemistry-readme-snapshot.mjs -->',
 '- 主库共有 **'+fmt(n)+'** 条候选记录：无机 **'+fmt(s.inorganic)+'**、分析 **'+fmt(s.analytical)+'**、物理 **'+fmt(s.physical)+'**、有机 **'+fmt(s.organic)+'**。',
 '- 其中 **'+fmt(k.exercise_candidate)+'** 条练习候选、**'+fmt(k.study_card)+'** 条学习卡；**不是** '+fmt(n)+' 道可以直接组卷的考试真题。',
 '- **'+fmt(n)+'** 条完成确定性来源及机器一致性复核；这不等于化学专家审核、语义去重完成或逐题具备再发布授权。',
 '- 全部待化学专家审核，publishable=false，正式批准 **0** 道。',
 '- [来源与质量审计](harvest/quality_audit.json) · [覆盖率](harvest/coverage_report.json) · [综合题科学条件专项检查](harvest/review_notes/original_multistep_science_review.md)。',
 '- 自动来源发现约每 10 分钟一次，严格候选入库约每 30 分钟一次，GitHub Actions 调度可能延迟。',
 '<!-- END GENERATED SNAPSHOT -->'
 ].join('\n');
}
export function rewrite(readme,q,v){
 const rx=/^## 当前候选内容快照[^\n]*\n[\s\S]*?(?=^## 原则[ \t]*$)/gm;
 const matches=[...readme.matchAll(rx)];
 if(matches.length!==1)throw Error('README snapshot heading missing or duplicated');
 return readme.replace(/^## 当前候选内容快照[^\n]*\n[\s\S]*?(?=^## 原则[ \t]*$)/m,snapshot(q,v)+'\n\n');
}
export function run(){
 const file=join(ROOT,'README.md');
 const before=readFileSync(file,'utf8');
 const next=rewrite(before,
  JSON.parse(readFileSync(join(ROOT,'harvest/quality_audit.json'),'utf8')),
  JSON.parse(readFileSync(join(ROOT,'harvest/coverage_report.json'),'utf8')));
 if(before!==next)writeFileSync(file,next);
 console.log('Audit-derived README snapshot updated; never changes question approval');
 return before!==next;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 try{run();}catch(e){console.error(e.stack);process.exitCode=1;}
}
